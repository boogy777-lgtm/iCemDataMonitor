            .ObserveOn(ctx)
            .Subscribe(x => ApplyStatusArea(x.banner, x.lost));
        ApplyStatusArea(_vm.ConnectionBanner, _vm.IsLost); // initial paint

        // «Перезапуск хоста» ⇄ RestartHost command: BUG1 law — enabled
        // whenever the HOST is alive (green AND orange-with-alive-host);
        // only the Down state (host not running) greys it out.
        RestartHostButton.Click += (_, _) => _vm.RestartHost.Execute().Subscribe();
        _vm.RestartHost.CanExecute
            .ObserveOn(ctx)
            .Subscribe(can => RestartHostButton.IsEnabled = can);

        // 2026-08-31 (decree 2): «Запустить хост» ⇄ LaunchHost command —
        // enabled ONLY in the Down state; the ensure-host flow runs shell-side.
