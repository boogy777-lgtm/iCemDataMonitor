            _syncingSwitches = false;
        });
        AutostartSwitch.IsEnabled = _vm.CanToggleAutostart;
        AutostartSwitch.Checked += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleAutostart.Execute().Subscribe();
        };
        AutostartSwitch.Unchecked += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleAutostart.Execute().Subscribe();
        };
    }

