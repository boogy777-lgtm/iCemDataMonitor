    private async Task InitPanelWebAsync()
    {
        try
        {
            // File IO off the UI thread; awaits resume on the dispatcher
            // (WinUI SynchronizationContext) — UI mutations below are safe.
            // ONE IniConfig.Load(): the D.4.3 search order (ProgramData →
            // next-to-exe, create-default) lives in Core — the shell neither
            // re-evaluates it nor rescans the file (a duplicate would be
            // drift). web_on is a REAL OPTIONAL schema key again (restored
            // 2026-08-27; default 1 since 2026-08-28): absent ⇒ 1, validate
            // 0..1 — so IniOptions.WebOn IS the flag, projected by the same
            // strict parser the host uses.
            var ini = await Task.Run(iCemDataMonitor.Core.Config.IniConfig.Load);

            if (ini.WebOn == 1)
            {
                await ShowWebDashboardAsync(ini.WebPort);
            }
            else
            {
                // web_on=0 (explicit — the default is now 1): an honest
                // muted note, the WebView core is never created.
                ShowWebPanelNote("Веб-панель выключена (web_on=0 в station.ini)");
            }
        }
        catch (Exception ex)
        {
            // Unreadable/invalid station.ini (IniConfigException lists EVERY
            // violation: unknown/duplicate/missing keys, non-numeric values —
            // e.g. a non-numeric web_on now surfaces HERE as a violation).
            // An honest error in the same section, never a silent fallback
            // and never a shell crash.
            ShowWebPanelNote($"Веб-панель недоступна: не удалось прочитать station.ini — {ex.Message}");
        }
    }

    private async Task ShowWebDashboardAsync(int webPort)
    {
        try
        {
            // One-shot core init (a missing WebView2 Runtime on the stand
            // lands here as an honest note — never as a crash).
            await PanelWebView.EnsureCoreWebView2Async();
            PanelWebView.Source = new Uri($"http://localhost:{webPort}/");
            PanelWebView.Visibility = Visibility.Visible;
            WebPageMessage.Visibility = Visibility.Collapsed;
            ShellLog($"[web] panel → http://localhost:{webPort}/");
        }
        catch (Exception ex)
        {
            PanelWebView.Visibility = Visibility.Collapsed;
            ShowWebPanelNote($"Веб-панель недоступна: не удалось инициализировать WebView2 — {ex.Message}");
        }
    }

