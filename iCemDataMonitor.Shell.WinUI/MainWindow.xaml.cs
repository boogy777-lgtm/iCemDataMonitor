        _vm.WhenAnyValue(x => x.ModbusOn).ObserveOn(ctx).Subscribe(v =>
        {
            _syncingSwitches = true;
            ModbusSwitch.IsOn = v;
            _syncingSwitches = false;
        });
        _vm.WhenAnyValue(x => x.SnifferOn).ObserveOn(ctx).Subscribe(v =>
        {
            _syncingSwitches = true;
            SnifferSwitch.IsOn = v;
            _syncingSwitches = false;
        });
        ModbusSwitch.IsEnabled = _vm.CanToggle;
        SnifferSwitch.IsEnabled = _vm.CanToggle;
        ModbusSwitch.Toggled += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleModbus.Execute().Subscribe();
        };
        SnifferSwitch.Toggled += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleSniffer.Execute().Subscribe();
        };

        // W21.4: console checkbox ⇄ host truth (same syncing-guard law).
        _vm.WhenAnyValue(x => x.ConsoleOn).ObserveOn(ctx).Subscribe(v =>
        {
            _syncingSwitches = true;
            ConsoleSwitch.IsChecked = v;
            _syncingSwitches = false;
        });
        ConsoleSwitch.IsEnabled = _vm.CanToggleConsole;
        ConsoleSwitch.Checked += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleConsole.Execute().Subscribe();
        };
        ConsoleSwitch.Unchecked += (_, _) =>
        {
            if (_syncingSwitches) return;
            _vm.ToggleConsole.Execute().Subscribe();
        };

        // 2026-08-27: autostart checkbox ⇄ host truth (HKCU Run key, same
