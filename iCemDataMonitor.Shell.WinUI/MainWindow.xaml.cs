    /// <summary>2026-08-31 (owner decree): the «Перезапуск хоста» button only
    /// SETS the host-owned named event — the host runs the IDENTICAL restart
    /// path as its tray [Перезапуск] (TrayActionGate + RestartPlan). A missing
    /// event means the host died between the health check and the click:
    /// honest log line, never a shell crash.</summary>
    private void SignalHostRestart()
    {
        try
        {
            using var ev = EventWaitHandle.OpenExisting(HostRestartEventName);
            ev.Set();
            ShellLog("[restart] host restart event signalled — the host restarts itself (tray path)");
        }
        catch (WaitHandleCannotBeOpenedException)
        {
            ShellLog("[restart] restart event not found — host is not running; nothing signalled");
        }
    }

    /// <summary>2026-08-31 (owner BUG1 decree): the host-liveness feed for the
    /// status area — 1 Hz probe (same cadence as the status ticks; the
    /// restart-budget decree «ускорить перезапуск» means the Down/alive flip
    /// must land within a second of the host actually changing state)
    /// through the SAME EnsureHost.Decide table the cold start uses (pipe
    /// GetStatus is authoritative; the mutex only refines the detail).
    /// Deliberately NOT the metrics FSM.</summary>
    private IObservable<bool> HostLivenessTicks() =>
        Observable.Interval(TimeSpan.FromSeconds(1))
            .Select(_ => Observable.FromAsync(ProbeHostAliveAsync))
            .StartWith(Observable.FromAsync(ProbeHostAliveAsync))
            .Concat();

    private async Task<bool> ProbeHostAliveAsync()
    {
        try
        {
            return await Task.Run(async () => !EnsureHost.ShouldSpawnNewHostProcess(
                EnsureHost.Decide(
                    mutexExists: EnsureHost.MutexExists(),
                    pipeResponds: await EnsureHost.PipeRespondsAsync(TimeSpan.FromMilliseconds(600)))));
        }
        catch
        {
            return false; // probe failure = cannot confirm liveness — honest Down
        }
    }

    // 2026-08-31 (decree 2): single-flight gate for the «Запустить хост» flow
    // (the VM command cannot gate re-entry across a session rebuild).
    private int _relaunchInFlight;

    /// <summary>2026-08-31 (decree 2): «Запустить хост» button flow — the SAME
    /// ensure-host path as the cold start (probe → connect | spawn + boot
    /// mirror), minus the fatal exit: the shell is already up, a failure stays
    /// an honest log line and the button remains available. On success the
    /// session is REBUILT (viewer → client, or a fresh client) — the new VM
    /// paints the new state; the old VM/session are disposed by
    /// CompleteWithSession's replacement law.</summary>
    private async Task LaunchHostFromButtonAsync()
    {
        if (Interlocked.Exchange(ref _relaunchInFlight, 1) == 1)
        {
            ShellLog("[launch] host launch already in flight — click ignored");
            return;
        }
        try
        {
            ShellLog("[launch] «Запустить хост» clicked — running the ensure-host flow");
            await ConnectOrCreateHostAsync(exitOnFailure: false);
        }
        finally
        {
            Interlocked.Exchange(ref _relaunchInFlight, 0);
        }
    }

    private static void ShellLog(string text) => App.ShellLog(text);

    // ── chrome (unchanged W14 code) ────────────────────────────────────────────

    // 2026-08-31 (owner decree): the toggle is now a TWO-STEP command over the
    // machine layer. Step 1 — the VISUAL (RequestedTheme + title bar), always
    // applied immediately (optimistic flip). Step 2 — the PERSIST, routed by
    // session kind: client mode ⇒ SetUiTheme RPC through session.ControlApi
    // (the HOST writes the shared ui-theme file + pokes the shell-owned
    // event — one writer, no shell/host double-write); viewer mode / host
    // Down ⇒ the file path as fallback (the shell is the writer, same as
    // before). A failed RPC degrades to the same fallback with an honest log
    // line — the station bool is never left silently stale.
    private void ThemeSwitch_Toggled(object sender, RoutedEventArgs e)
    {
        if (_syncingSwitches) return; // programmatic sync (listener/ctor) — no persist
        var light = ThemeSwitch.IsOn;
        ApplyTheme(light);

        var control = Session?.ControlApi;
        if (control is null)
        {
            SaveTheme(light); // fallback: viewer / host Down — shell owns the write
            return;
        }
        _ = SetThemeViaHostAsync(control, light);
    }

    /// <summary>2026-08-31: client-mode persist — SetUiThemeAsync; the host
    /// writes ui-theme and pokes Local\iCemDataMonitorTray_v1_UiTheme, so the
    /// shell's own StartThemeListener re-reads the file and its echo branch
    /// (light == ThemeSwitch.IsOn) terminates without a second write.</summary>
    private async Task SetThemeViaHostAsync(GrpcHostClient control, bool light)
    {
        try
        {
            var reply = await control.SetUiThemeAsync(light).ConfigureAwait(true);
            _syncingSwitches = true;
            ThemeSwitch.IsOn = reply.ThemeLight;
            _syncingSwitches = false;
            ApplyTheme(reply.ThemeLight);
            ShellLog($"[theme] current host theme: {(reply.ThemeLight ? "light" : "dark")}");
        }
        catch (Exception ex)
        {
            // Host died / went unreachable between the toggle and the RPC:
            // honest log + the SAME file path the viewer mode uses — the
            // station bool still lands, the event still pokes live listeners.
            ShellLog($"[theme] host write FAILED ({ex.Message}) — file fallback");
            SaveTheme(light);
        }
    }

    /// <summary>VISUAL application only (2026-08-31): persistence moved OUT —
    /// ApplyTheme must not write: the ctor reads the file (a read must not
    /// re-persist) and the event listener receives ALREADY-persisted truth
    /// (the writer poked after its write). The toggle handler owns persisting.</summary>
    private void ApplyTheme(bool light)
    {
        var theme = light ? ElementTheme.Light : ElementTheme.Dark;
        RootGrid.RequestedTheme = theme;
        ApplyTitleBarTheme(light);
    }

    private void ApplyTitleBarTheme(bool light)
    {
        static Windows.UI.Color C(uint argb) => Windows.UI.Color.FromArgb(
            (byte)(argb >> 24), (byte)(argb >> 16), (byte)(argb >> 8), (byte)argb);

        var bg = light ? C(0xFFF5F5F7) : C(0xFF1E1E1E);          // MacWindow
        var fg = light ? C(0xD9000000) : C(0xFFF5F5F5);          // MacLabel
        var fgInactive = light ? C(0x66000000) : C(0xFF666666);  // MacLabel3
        var hover = light ? C(0xFFF0F0F2) : C(0xFF272729);       // MacSurface2
        var pressed = light ? C(0xFFE0E0E4) : C(0xFF3A3A3C);     // step beyond hover

        var tb = AppWindow.TitleBar;
        tb.BackgroundColor = bg;
        tb.InactiveBackgroundColor = bg;
        tb.ForegroundColor = fg;
        tb.InactiveForegroundColor = fgInactive;
        tb.ButtonBackgroundColor = bg;
        tb.ButtonInactiveBackgroundColor = bg;
        tb.ButtonForegroundColor = fg;
        tb.ButtonInactiveForegroundColor = fgInactive;
        tb.ButtonHoverBackgroundColor = hover;
        tb.ButtonHoverForegroundColor = fg;
        tb.ButtonPressedBackgroundColor = pressed;
        tb.ButtonPressedForegroundColor = fg;
    }

    // 2026-08-31 (owner decree «даже смена темы — тоже CLI»): the theme is a
    // STATION-WIDE shared bool — ui-theme next to config.ini (the ProgramData
    // station root), so EVERY UI surface (this WinUI shell today; the web SPA
    // via its upcoming reader) sees the SAME truth. The old next-to-exe
    // mac-theme was per-exe: invisible to any other surface. Migration: a
    // legacy mac-theme is ADOPTED once (copy semantics — the old file stays,
    // inert), exactly like the station.ini → config.ini law.
    private static string ThemeFilePath() =>
        Path.Combine(
            Path.GetDirectoryName(iCemDataMonitor.Core.Config.IniConfig.ProgramDataPath)!,
            "ui-theme");

    private static string LegacyThemeFilePath() =>
        Path.Combine(AppContext.BaseDirectory, "mac-theme");

    // The poke event making the flip SIMULTANEOUS across live UIs: the writer
    // saves the bool first, then SETs; every listener re-reads the file.
    // Same event-poke pattern as the shell shutdown event, but ANY UI may set
    // it (writer = whoever toggled). OWNER: the shell (creates + waits).
    private const string UiThemeChangedEventName = @"Local\iCemDataMonitorTray_v1_UiTheme";

    private readonly System.Threading.ManualResetEventSlim _themeListenerStop = new();

    private static bool LoadThemeIsLight()
    {
        try
        {
            var shared = ThemeFilePath();
            if (!File.Exists(shared))
            {
                // One-time adoption of the per-exe legacy file (copy, ¬ move).
                var legacy = LegacyThemeFilePath();
                if (File.Exists(legacy))
                {
                    var legacyValue = File.ReadAllText(legacy).Trim();
                    try { File.WriteAllText(shared, legacyValue); } catch { /* best effort */ }
                    return legacyValue == "light";
                }
                return false; // default = dark (matches the web default)
            }
            return File.ReadAllText(shared).Trim() == "light";
        }
        catch { return false; } // default = dark
    }

    private static void SaveTheme(bool light)
    {
        try { File.WriteAllText(ThemeFilePath(), light ? "light" : "dark"); }
        catch { /* best effort */ }
        // 2026-08-31: poke AFTER the bool is durable — listeners re-read the
        // file. No listener (sole UI alive) is fine — the next UI adopts the
        // file value at startup anyway.
        try
        {
            using var ev = EventWaitHandle.OpenExisting(UiThemeChangedEventName);
            ev.Set();
        }
        catch (WaitHandleCannotBeOpenedException) { /* nobody listening — ok */ }
        catch { /* cosmetic */ }
    }

    /// <summary>2026-08-31 (shared theme bool): listen for theme pokes from
    /// OTHER UI surfaces (a second shell instance is impossible, but the
    /// pattern is the same one the web SPA will use) and apply the shared
    /// truth. Idempotent: an unchanged value is a no-op, so a poke echo of
    /// our own toggle terminates immediately.</summary>
    private void StartThemeListener()
    {
        var themeEvent = new EventWaitHandle(false, EventResetMode.AutoReset, UiThemeChangedEventName);
        themeEvent.Reset(); // P4 lesson: drop a stale Set from a previous shell lifetime
        Closed += (_, _) => _themeListenerStop.Set();
        _ = Task.Run(() =>
        {
            while (WaitHandle.WaitAny(new WaitHandle[] { themeEvent, _themeListenerStop.WaitHandle }) == 0)
            {
                var light = LoadThemeIsLight();
                DispatcherQueue.TryEnqueue(() =>
                {
                    if (light == ThemeSwitch.IsOn)
                        return; // echo of our own toggle / no real change
                    // 2026-08-31: the incoming truth is ALREADY persisted (the
                    // writer poked AFTER its write) — the switch flip is
                    // guarded (_syncingSwitches) so Toggled never re-persists,
                    // then the visual applies. Idempotent by construction.
                    _syncingSwitches = true;
                    ThemeSwitch.IsOn = light;
                    _syncingSwitches = false;
                    ApplyTheme(light);
                });
            }
            themeEvent.Dispose();
        });
    }

