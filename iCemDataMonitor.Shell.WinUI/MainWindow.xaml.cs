    private void BuildViewModel(ShellSession session)
    {
        var degraded = session.Mode == ShellSession.ModeKind.ViewerOnly;
        _vm = new HostStatusViewModel(
            statusTicks: session.StatusTicks(),
            samples: session.Link?.Samples,
            linkStates: session.Link?.States,
            watchdogTicks: Observable.Interval(TimeSpan.FromSeconds(1)).Select(_ => Unit.Default),
            control: session.ControlApi,
            degradedMode: degraded,
            // W21.4: console checkbox → SetConsoleVisible RPC (client mode only).
            setConsoleVisible: session.ControlApi is null
                ? null
                : async visible => await session.ControlApi!.SetConsoleVisibleAsync(visible),
            // 2026-08-27: autostart checkbox → SetAutostart RPC (client mode only).
            setAutostart: session.ControlApi is null
                ? null
                : async enabled => await session.ControlApi!.SetAutostartAsync(enabled),
            // 2026-08-31 (owner decree): «Перезапуск хоста» button → named
            // event poke (client mode only — viewer mode has no host to
            // restart, the VM greys the button out via CanRestartHost).
            signalHostRestart: session.ControlApi is null ? null : SignalHostRestart,
            // 2026-08-31 (owner BUG1 decree): host liveness = the PIPE probe
            // (GetStatus + mutex, every ~2 s), NOT the metrics FSM — the
            // stream aborts with UNAVAILABLE on a closed bus while the host
            // serves GetStatus fine (that conflation disabled «Перезапуск
            // хоста» on a healthy host). Viewer mode: no probe (its state is
            // pinned Down by the degraded-mode law).
            hostAlive: session.ControlApi is null ? null : HostLivenessTicks(),
            // 2026-08-31 (decree 2): «Запустить хост» — both session kinds
            // pass the delegate (client: the host died while the shell was
            // open; viewer: the sanctioned way out of the read-only mode).
            launchHost: LaunchHostFromButtonAsync);

        var ctx = SynchronizationContext.Current!;
        _vm.WhenAnyValue(x => x.BusText).ObserveOn(ctx).Subscribe(t => BusFact.Text = t);
        _vm.WhenAnyValue(x => x.ComText).ObserveOn(ctx).Subscribe(t => ComFact.Text = t);
        _vm.WhenAnyValue(x => x.LanText).ObserveOn(ctx).Subscribe(t => LanFact.Text = t);
        _vm.WhenAnyValue(x => x.RawText).ObserveOn(ctx).Subscribe(t => RawFact.Text = t);
        _vm.WhenAnyValue(x => x.ModbusText).ObserveOn(ctx).Subscribe(t => ModbusText.Text = t);
        _vm.WhenAnyValue(x => x.SnifferText).ObserveOn(ctx).Subscribe(t => SnifferText.Text = t);
        _vm.WhenAnyValue(x => x.OpcText).ObserveOn(ctx).Subscribe(t => OpcText.Text = t);
