    private void CompleteWithSession(ShellSession session)
    {
        // 2026-08-31 (decree 2): session REPLACEMENT law — the «Запустить
        // хост» button rebuilds the session (viewer → client, or a fresh
        // client after the host died). The OLD VM/session are disposed AFTER
        // the new ones are built (no UI gap, no double-dispose of nulls).
        var oldVm = _vm;
        var oldSession = Session;
        Session = session;
        // TOMBSTONE (2026-08-27): EmulatorViewModel.EngineControl wiring +
        // the engine-control adapter composition REMOVED — the emulator is a
        // separate independent app; the shell has no engine control channel.
        BuildViewModel(session);
        oldVm?.Dispose();
        oldSession?.Dispose();
        SessionReady?.Invoke(session);
        // W21.4: a section may have been requested while the shell was away
        // (tray [Статус] / CLI stored it as pending) — consume it on first show.
        _ = ApplyPendingNavigationAsync();
    }

    // ── pending navigation (W21.4) ─────────────────────────────────────────────

    /// <summary>Query arm of NavigateUi: read-and-clear the pending section the
    /// HOST stored and open it. The shell is a dumb view — the host decides.</summary>
    public async Task ApplyPendingNavigationAsync()
    {
        if (Session?.ControlApi is null)
            return; // viewer mode has no host channel — nothing to query
        try
        {
            var r = await Session.ControlApi.NavigateUiAsync(iCemDataMonitor.Contracts.UiSection.Unspecified);
            var tag = TagOf(r.Pending);
            if (tag is not null)
            {
                ShellLog($"[nav] applying pending={r.Pending} → tag '{tag}'");
                DispatcherQueue.TryEnqueue(() => SelectNavTag(tag));
            }
        }
        catch (Exception ex)
        {
            ShellLog($"[nav] pending query failed (non-fatal): {ex.Message}");
        }
    }

    private static string? TagOf(iCemDataMonitor.Contracts.UiSection section) => section switch
    {
        iCemDataMonitor.Contracts.UiSection.Status => "status",
        // Corrected decree 2026-08-27: the host may carry a pending WEB
        // section again (tray [Открыть Web] / NavigateUi) → the «Панель» tab.
        iCemDataMonitor.Contracts.UiSection.Web => "web",
        _ => null, // Unspecified → nothing pending
    };

    private void SelectNavTag(string tag)
    {
        foreach (var item in Nav.MenuItems.OfType<NavigationViewItem>())
        {
            if ((item.Tag as string) == tag)
            {
                Nav.SelectedItem = item;
                return;
            }
        }
    }

