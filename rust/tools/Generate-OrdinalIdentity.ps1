# Exhaustive BCL oracle; no Unicode casing library is substituted for the comparer.
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$tablePath = Join-Path $root 'crates/icem-emulation/src/identity_table.rs'
Add-Type -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;
public static class OrdinalIdentityGenerator
{
    public static string Generate()
    {
        // One representative per class. Dictionary resolves hash collisions with the
        // real comparer: hash equality is never treated as string equality.
        var classes = new Dictionary<string, int>(0x110000 - 0x800, StringComparer.OrdinalIgnoreCase);
        var output = new StringBuilder("// Generated by tools/Generate-OrdinalIdentity.ps1. Do not edit.\n// Minimal scalar representative of each nontrivial OrdinalIgnoreCase class.\npub(super) const MAPPINGS: &[(char, char)] = &[\n");
        int count = 0;
        int changed = 0;
        for (int scalar = 0; scalar <= 0x10ffff; scalar++)
        {
            if (scalar >= 0xd800 && scalar <= 0xdfff) continue;
            count++;
            string value = char.ConvertFromUtf32(scalar);
            if (!classes.TryGetValue(value, out int representative))
            {
                classes.Add(value, scalar);
                representative = scalar;
            }
            if (representative > scalar) throw new InvalidOperationException("Nonminimal class");
            string key = char.ConvertFromUtf32(representative);
            if (value.Length != key.Length || !StringComparer.OrdinalIgnoreCase.Equals(value, key))
                throw new InvalidOperationException("Invalid scalar representative");
            // Exercise BMP/surrogate boundaries, embedded NUL and combining mark.
            // Source algorithm compares BMP units or valid surrogate pairs without
            // context, expansions or normalization; these also guard that contract.
            if (!StringComparer.OrdinalIgnoreCase.Equals("\0a\U00010400" + value + "\u0301Z", "\0A\U00010428" + key + "\u0301z"))
                throw new InvalidOperationException("String composition mismatch at " + scalar);
            if (representative != scalar)
            {
                changed++;
                output.Append("    ('\\u{").Append(scalar.ToString("x", CultureInfo.InvariantCulture))
                    .Append("}', '\\u{").Append(representative.ToString("x", CultureInfo.InvariantCulture)).Append("}'),\n");
            }
        }
        if (count != 1112064) throw new InvalidOperationException("Incomplete scalar coverage");
        output.Append("];\n");
        Console.Error.WriteLine("scalars=" + count + "; mappings=" + changed + "; classes=" + classes.Count);
        return output.ToString();
    }
    public static string Provider()
    {
        var type = typeof(string).Assembly.GetType("System.Globalization.GlobalizationMode", true);
        var flags = BindingFlags.Static | BindingFlags.NonPublic | BindingFlags.Public;
        return "Invariant=" + type.GetProperty("Invariant", flags).GetValue(null)
            + "; UseNls=" + (type.GetProperty("UseNls", flags)?.GetValue(null)?.ToString() ?? "unavailable");
    }
}
'@
$data = [OrdinalIdentityGenerator]::Generate()
Write-Host ([Runtime.InteropServices.RuntimeInformation]::FrameworkDescription)
Write-Host ([Runtime.InteropServices.RuntimeInformation]::OSDescription)
Write-Host ([OrdinalIdentityGenerator]::Provider())
Write-Host ('Invariant sort version=' + [Globalization.CultureInfo]::InvariantCulture.CompareInfo.Version.FullVersion)
if ($Check) {
    if (![IO.File]::Exists($tablePath) -or [IO.File]::ReadAllText($tablePath).Replace("`r`n", "`n") -cne $data) {
        throw 'OrdinalIgnoreCase provider drift or generated table changed. Review baseline and Windows evidence; do not silently regenerate.'
    }
    Write-Host 'PASS: every valid scalar class and contextual witness matches checked-in table.'
} else {
    [IO.File]::WriteAllText($tablePath, $data, [Text.UTF8Encoding]::new($false))
}
